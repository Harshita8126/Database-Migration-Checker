"""
Safe SQL Generator & Migration Rewriter.


Generates safer SQL alternatives:
- Preserves original SQL untouched.
- Produces clean, executable alternative SQL scripts.
- Adds lock_timeout safety guards.
- Replaces write-blocking commands with concurrent and multi-step equivalents.
- Adds informative inline comments explaining the safety mechanics.
"""

from typing import List, Dict, Any
from backend.parser import parse_sql_migration


def generate_safe_migration_script(
    original_sql: str,
    issues: List[Dict[str, Any]],
    has_lock_timeout: bool
) -> Dict[str, Any]:
    """
    Constructs a complete safe alternative migration script with safety preambles
    and safe SQL replacements for flagged issues.
    """
    safe_lines: List[str] = []

    # 1. Preamble guardrails
    safe_lines.append("-- ========================================================")
    safe_lines.append("-- SAFE MIGRATION SCRIPT (Generated by Migration Safety Checker)")
    safe_lines.append("-- ========================================================\n")

    if not has_lock_timeout:
        safe_lines.append("-- [Safety Guard] Prevent lock queue disasters and connection exhaustion")
        safe_lines.append("SET lock_timeout = '3s';")
        safe_lines.append("SET statement_timeout = '30s';\n")

    # Map original raw sql to safe sql replacement
    replacement_map = {}
    for issue in issues:
        orig = (issue.get("original_sql") or "").strip()
        safe = (issue.get("safe_sql") or "").strip()
        if orig and safe and orig != "-- (Missing at beginning of script)":
            replacement_map[orig] = {
                "safe_sql": safe,
                "rule_name": issue.get("rule_name"),
                "reason": issue.get("reason"),
            }

    # Parse statements to reconstruct or replace
    parse_res = parse_sql_migration(original_sql)
    
    if not parse_res.success or not parse_res.statements:
        # Fallback: combine all safe_sql snippets from issues
        for issue in issues:
            if issue.get("safe_sql"):
                safe_lines.append(f"-- Fix for {issue.get('rule_name')}:")
                safe_lines.append(issue.get("safe_sql"))
                safe_lines.append("")
    else:
        for stmt in parse_res.statements:
            raw = stmt.raw_sql.strip()
            # If this statement has a safe replacement
            if raw in replacement_map:
                info = replacement_map[raw]
                safe_lines.append(f"-- >>> [SAFETY REWRITE] Rule: {info['rule_name']}")
                safe_lines.append(f"-- Original: {raw}")
                safe_lines.append(info['safe_sql'])
                safe_lines.append("")
            else:
                # Statement was clean, keep it as is
                safe_lines.append(f"-- Statement (Passed safety checks)")
                safe_lines.append(raw)
                safe_lines.append("")

    full_safe_sql = "\n".join(safe_lines)

    return {
        "safe_script": full_safe_sql,
        "replacements_count": len(replacement_map),
        "has_lock_guards": True,
    }
